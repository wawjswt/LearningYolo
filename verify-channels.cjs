const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({window:{lessonPlaygrounds:{render:()=>'',initialize(){}}},document:{addEventListener(){},querySelectorAll:()=>[]}});
vm.runInContext(fs.readFileSync('dist/textbook-channels.js','utf8'),context);
const {shape, compute} = context.window.channelConvolution;
const video = shape(3,16,3,1,0,1);
assert.equal(video.size,5);
assert.equal(video.parameters,448);
assert.equal(video.depth,3);
assert.equal(shape(8,16,3,1,0,2).parameters,592);
assert.equal(shape(8,8,3,1,0,8).parameters,80);
assert.equal(shape(3,16,1,1,0,1).parameters,64);
assert.equal(shape(3,16,3,2,1,1).size,4);
assert.throws(()=>shape(3,16,3,1,0,2));
const first = compute(0,0,0,[true,true,true],1);
assert.deepEqual(Array.from(first.parts),[2,3,4]);
assert.equal(first.value,10);
assert.equal(compute(1,0,0,[true,true,true],-1).value,2);
assert.equal(compute(0,0,0,[true,false,true],1).value,7);
assert.equal(compute(0,1,1,[false,false,false],-2).value,-2);
assert.match(context.window.lessonPlaygrounds.render('cnn',1),/data-channel-shape/);
assert.match(context.window.lessonPlaygrounds.render('cnn',4),/data-channel-math/);
vm.runInContext(fs.readFileSync('dist/data.js','utf8')+fs.readFileSync('dist/textbook-v2.js','utf8')+fs.readFileSync('dist/textbook-exercises.js','utf8'),context);
const cnn=vm.runInContext('lessons.find(l=>l.id==="cnn")',context);
assert.equal(cnn.sections.length,7);
for(const section of cnn.sections)assert.ok(section.exercise?.why);
console.log('Channel lesson: shapes, group constraints, cross-channel sums, masking and exercise coverage passed.');
